"""Dry-run scaffold for AI grading autoresearch records.

This script intentionally does not run models, rebuild packets, or inspect raw
Data/ submissions. It assembles a reproducible planning record from tracked
metadata so the real orchestrator has a stable target shape.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


RECORD_TYPE = "ai_grading_autoresearch_experiment"
DEFAULT_DEV_PACKETS = ("T1-dev-r1", "G1-dev-r1")
DEFAULT_HELDOUT_PACKETS = ("T1-test-r1", "G1-test-r1")


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if args.mode != "dry-run":
        print(
            "execute mode is intentionally not implemented in this design scaffold",
            file=sys.stderr,
        )
        return 2

    repo_root = find_repo_root(Path.cwd())
    record = build_record(args, repo_root)
    payload = json.dumps(record, indent=2, sort_keys=True) + "\n"

    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(payload, encoding="utf-8", newline="\n")
    else:
        print(payload, end="")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Build a dry-run AI grading autoresearch experiment record."
    )
    parser.add_argument("--mode", choices=("dry-run", "execute"), default="dry-run")
    parser.add_argument("--record-id", required=True)
    parser.add_argument(
        "--candidate-id",
        default="skill_candidate_autoresearch_0001",
    )
    parser.add_argument(
        "--course-spec",
        type=Path,
        required=True,
        help="Tracked course spec JSON, not raw data.",
    )
    parser.add_argument(
        "--data-inventory",
        type=Path,
        required=True,
        help="Tracked privacy-preserving data inventory JSON.",
    )
    parser.add_argument("--baseline-skill", type=Path, required=True)
    parser.add_argument("--candidate-skill", type=Path, required=True)
    parser.add_argument(
        "--generated-at",
        help="ISO-8601 UTC timestamp. Defaults to current time.",
    )
    parser.add_argument("--output", type=Path)
    return parser


def build_record(args: argparse.Namespace, repo_root: Path) -> dict[str, Any]:
    course = read_json(resolve(repo_root, args.course_spec))
    inventory = read_json(resolve(repo_root, args.data_inventory))
    baseline_skill = read_json(resolve(repo_root, args.baseline_skill))
    candidate_skill = read_json(resolve(repo_root, args.candidate_skill))

    generated_at = args.generated_at or utc_now()
    git = git_state(repo_root)
    return {
        "schema_version": 1,
        "record_type": RECORD_TYPE,
        "record_id": args.record_id,
        "generated_at": generated_at,
        "mode": args.mode,
        "git": git,
        "scope": {
            "course_id": course["course_id"],
            "assessment_id": course["assessment_id"],
            "course_spec_path": relative_or_posix(args.course_spec),
            "data_inventory_path": relative_or_posix(args.data_inventory),
            "data_snapshot_hash": inventory["snapshot_hash"],
            "raw_data_policy": "Do not inspect or copy raw Data/ submissions in this scaffold.",
        },
        "candidate": {
            "candidate_id": args.candidate_id,
            "baseline_skill": skill_summary(args.baseline_skill, baseline_skill),
            "candidate_skill": skill_summary(args.candidate_skill, candidate_skill),
            "editable_surface": [
                ".agents/skills/grade-homework/",
                ".claude/skills/grade-homework/",
                "experiments/prompt_templates/grade_candidate_*.txt",
                "experiments/skill_versions/skill_candidate_*.json",
                "experiments/records/",
            ],
            "generation_status": "planned; no candidate generated by this scaffold",
        },
        "prompt_packets": {
            "policy": "Blind packets only; no gold scores, identity maps, metrics, reports, or previous predictions.",
            "development": {
                "status": "planned",
                "packet_ids": list(DEFAULT_DEV_PACKETS),
            },
            "heldout": {
                "status": "locked_until_development_gate_passes",
                "packet_ids": list(DEFAULT_HELDOUT_PACKETS),
            },
        },
        "metrics": {
            "primary": "total_score_mae",
            "guardrails": [
                "subquestion_mae",
                "exact_agreement",
                "within_1_point_rate",
                "severe_error_rate",
                "mean_signed_error",
                "missing_output_count",
                "invalid_output_count",
            ],
        },
        "gates": {
            "development": {
                "status": "not_run",
                "criteria": [
                    "packet audit passes",
                    "all outputs validate against output.schema.json",
                    "candidate total_score_mae is lower than baseline",
                    "severe_error_rate does not increase",
                    "missing and invalid outputs are zero",
                    "candidate diff remains bounded to the editable surface",
                ],
            },
            "heldout": {
                "status": "locked",
                "criteria": [
                    "development gate passed",
                    "candidate snapshot is frozen",
                    "held-out packets are run once without tuning feedback",
                    "held-out result is recorded even if candidate is rejected",
                ],
            },
        },
        "orchestration": {
            "skillopt": {
                "status": "design_only",
                "instructions": "Generate one bounded candidate skill change, snapshot it, run dev metrics, then keep or reject.",
            },
            "codex_headless": {
                "status": "template_only",
                "command": [
                    "codex",
                    "exec",
                    "--full-auto",
                    "--prompt-file",
                    "experiments/records/autoresearch-design/program.md",
                ],
            },
            "claude_headless": {
                "status": "template_only",
                "command": [
                    "claude",
                    "-p",
                    "READ experiments/records/autoresearch-design/program.md AND RUN ONE DRY-RUN SKILLOPT ITERATION",
                ],
            },
        },
        "decision": {
            "status": "not_evaluated",
            "reason": "dry-run scaffold only; no model outputs or metrics were produced",
            "rollback_policy": "Rejected real candidates must keep an experiment record, preserve audit outputs, and restore the last accepted candidate.",
        },
        "artifacts": {
            "program_path": "experiments/records/autoresearch-design/program.md",
            "schema_path": "experiments/records/autoresearch-design/schema.json",
            "run_script_path": "experiments/records/autoresearch-design/run_experiment.py",
            "output_path": relative_or_posix(args.output) if args.output else None,
        },
    }


def skill_summary(path: Path, payload: dict[str, Any]) -> dict[str, str]:
    return {
        "path": relative_or_posix(path),
        "skill_version_id": payload["skill_version_id"],
        "canonical_hash": payload["canonical_hash"],
    }


def read_json(path: Path) -> dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError(f"JSON object required: {path}")
    return payload


def find_repo_root(start: Path) -> Path:
    result = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],
        cwd=start,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        check=False,
    )
    if result.returncode == 0 and result.stdout.strip():
        return Path(result.stdout.strip())
    return start


def git_state(repo_root: Path) -> dict[str, Any]:
    branch = git(repo_root, "branch", "--show-current")
    commit = git(repo_root, "rev-parse", "HEAD")
    status = git(repo_root, "status", "--short")
    status_lines = [line for line in status.splitlines() if line.strip()]
    return {
        "branch": branch or None,
        "commit": commit or None,
        "dirty": bool(status_lines),
        "status_summary": status_lines,
    }


def git(repo_root: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", *args],
        cwd=repo_root,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        return ""
    return result.stdout.strip()


def resolve(repo_root: Path, path: Path) -> Path:
    return path if path.is_absolute() else repo_root / path


def relative_or_posix(path: Path | None) -> str | None:
    if path is None:
        return None
    return path.as_posix()


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


if __name__ == "__main__":
    raise SystemExit(main())
